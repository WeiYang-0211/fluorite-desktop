using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;
using System.Text.RegularExpressions;
using Launchpad.Models;

namespace Launchpad.Services;

public static class IconPackService
{
	private static readonly string[] ImageExts = new string[4] { ".exe", ".lnk", ".url", ".appref-ms" };

	private static readonly Regex NoiseStem = new Regex("^(unins\\d*|uninstall|installer|setup|update|updater|crashpad|crashReporter|helper|helpers|notification|bugsnag|squirrel|elevate|vcredist|install)$", RegexOptions.IgnoreCase | RegexOptions.Compiled);

	private static readonly Regex AumidShape = new Regex("^[\\w.]+_[\\w.]+!\\w", RegexOptions.Compiled);

	private static readonly Dictionary<string, IconPack> _loaded = new Dictionary<string, IconPack>(StringComparer.OrdinalIgnoreCase);

	private static DateTime _scannedAt = DateTime.MinValue;

	public static string OfficialDirectory => Path.Combine(AppContext.BaseDirectory, "Assets", "IconPacks");

	public static string UserDirectory => Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "Fluorite", "icon-packs");

	public static IReadOnlyList<IconPack> ListPacks()
	{
		if (DateTime.Now - _scannedAt < TimeSpan.FromMinutes(1.0))
		{
			return _loaded.Values.ToList();
		}
		_scannedAt = DateTime.Now;
		_loaded.Clear();
		bool[] entries = new bool[2] { true, false };
		foreach (bool validated in entries)
		{
			string path = (validated ? OfficialDirectory : UserDirectory);
			if (!Directory.Exists(path))
			{
				continue;
			}
			foreach (string item in from d in Directory.EnumerateDirectories(path)
				orderby d
				select d)
			{
				IconPack iconPack = TryLoad(item, validated);
				if (iconPack != null && !_loaded.ContainsKey(iconPack.Id))
				{
					_loaded[iconPack.Id] = iconPack;
				}
			}
		}
		return _loaded.Values.OrderByDescending((IconPack p) => p.IsOfficial).ThenBy((IconPack p) => p.Name, StringComparer.Ordinal).ToList();
	}

	public static void Invalidate()
	{
		_scannedAt = DateTime.MinValue;
	}

	public static IconPack? Find(string? id)
	{
		if (string.IsNullOrWhiteSpace(id))
		{
			return null;
		}
		foreach (IconPack item in ListPacks())
		{
			if (string.Equals(item.Id, id, StringComparison.OrdinalIgnoreCase))
			{
				return item;
			}
		}
		return null;
	}

	public static string? ResolveImageFile(IconPack pack, AppItem app)
	{
		foreach (string item in MatchKeys(app))
		{
			if (pack.Icons.TryGetValue(item, out string value) && File.Exists(value))
			{
				return value;
			}
		}
		if (pack.DefaultFile == null || !File.Exists(pack.DefaultFile))
		{
			return null;
		}
		return pack.DefaultFile;
	}

	private static IconPack? TryLoad(string directory, bool official)
	{
		string text = Path.Combine(directory, "pack.json");
		if (!File.Exists(text))
		{
			return null;
		}
		try
		{
			using JsonDocument jsonDocument = JsonDocument.Parse(File.ReadAllText(text));
			JsonElement rootElement = jsonDocument.RootElement;
			string commandLinePath = ReadString(rootElement, "id") ?? Path.GetFileName(directory);
			string name = ReadString(rootElement, "name") ?? commandLinePath;
			Dictionary<string, string> dictionary = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
			if (rootElement.TryGetProperty("icons", out var value) && value.ValueKind == JsonValueKind.Object)
			{
				foreach (JsonProperty item in value.EnumerateObject())
				{
					if (item.Value.ValueKind == JsonValueKind.String)
					{
						string key = (item.Name.Contains(':') ? item.Name : ("exe:" + item.Name));
						string text3 = WorkspaceLibrary.ResolveInside(directory, item.Value.GetString());
						if (File.Exists(text3))
						{
							dictionary[key] = text3;
						}
					}
				}
			}
			string text4 = ReadString(rootElement, "default");
			string text5 = ((text4 == null) ? null : WorkspaceLibrary.ResolveInside(directory, text4));
			return new IconPack
			{
				Id = commandLinePath,
				Name = name,
				RootDirectory = directory,
				Icons = dictionary,
				DefaultFile = ((text5 != null && File.Exists(text5)) ? text5 : null),
				Stamp = File.GetLastWriteTimeUtc(text),
				IsOfficial = official
			};
		}
		catch (Exception ex)
		{
			App.Log("[PACK] cannot read " + text + ": " + ex.Message);
			return null;
		}
	}

	private static string? ReadString(JsonElement target, string prop)
	{
		if (!target.TryGetProperty(prop, out var value) || value.ValueKind != JsonValueKind.String)
		{
			return null;
		}
		return value.GetString();
	}

	internal static IEnumerable<string> MatchKeys(AppItem app)
	{
		string text = (app.ExecutablePath ?? string.Empty).Trim();
		if (text.Length == 0)
		{
			yield break;
		}
		if (app.Source == "UWP" || AumidShape.IsMatch(text))
		{
			if (!Regex.IsMatch(text, "AutoGenerated", RegexOptions.IgnoreCase))
			{
				string commandLinePath = text.Split('!')[0];
				int pageNumber = commandLinePath.LastIndexOf('_');
				if (pageNumber >= 0)
				{
					commandLinePath = commandLinePath.Substring(0, pageNumber);
				}
				if (!Regex.IsMatch(commandLinePath, "^https?:", RegexOptions.IgnoreCase))
				{
					yield return "uwp:" + commandLinePath;
				}
			}
			yield break;
		}
		string text3 = text;
		try
		{
			text3 = Uri.UnescapeDataString(text3.Split('?')[0]);
		}
		catch
		{
		}
		string text4 = Path.GetExtension(text3).ToLowerInvariant();
		string text5 = (Enumerable.Contains(ImageExts, text4) ? Path.GetFileNameWithoutExtension(text3) : Path.GetFileName(text3)).Trim();
		if (text5.Length != 0 && !NoiseStem.IsMatch(text5))
		{
			bool validated;
			switch (text4)
			{
			case ".lnk":
			case ".url":
			case ".appref-ms":
				validated = true;
				break;
			default:
				validated = false;
				break;
			}
			string text6 = (validated ? "shell" : "exe");
			yield return text6 + ":" + text5;
		}
	}
}
